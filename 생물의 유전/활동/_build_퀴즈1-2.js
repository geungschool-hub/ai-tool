ok(quiz.id === '유전1-2_사람의유전_퀴즈', 'id 가 정해진 값이다');
ok(quiz.id !== '유전1-1_유전의기본원리_퀴즈', '★기존 1-1 퀴즈와 다른 id 다 (덮어쓰지 않는다)');
ok(!!quiz.title && !!quiz.subtitle && !!quiz.unit, '제목·부제·단원이 있다');
ok(new Set(questions.map(x => x.chapter)).size === 4, 'chapter 가 4갈래다');
ok(quiz.order === 60, '★목록 차례가 1-1(order 50) 다음이다');
ok(quiz.unit === 'Ⅰ. 유전자와 유전물질' && quiz.unitColor === 'blue',
   '단원·색이 1-1 과 같다 (같은 Ⅰ단원으로 묶인다)');

console.log('');
console.log('결과: ' + pass + ' 통과, ' + fail + ' 실패');
if (fail) process.exit(1);

